//! The `.quarto-source.yml` install record (bd-rfz4e3bw).
//!
//! `q2 add` writes one next to each extension it installs, at
//! `_extensions/[<org>/]<name>/.quarto-source.yml`, and never touches
//! the author's `_extension.yml`. It answers two questions later:
//!
//! - **Where did this come from?** `source`, `kind`, and `ref`, for a
//!   future `q2 update`.
//! - **Has it been edited since?** A sha256 per installed file. Before
//!   replacing an installed extension, `q2 add` re-hashes it; any
//!   difference is a local edit, and replacing it needs `--force`.
//!
//! Quarto 1 records nothing, so an extension it installed has no
//! record. That case is reported as "untracked" rather than refused —
//! see [`InstalledState`].

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::commands::common::plan::CommandFailure;

pub const RECORD_FILENAME: &str = ".quarto-source.yml";

/// Written above the YAML body so someone who opens the file knows it
/// is machine-owned and what editing it would break.
const RECORD_HEADER: &str = "\
# Generated by `q2 add`. Do not edit.
#
# Records where this extension was installed from, and a sha256 of each
# installed file. Before replacing this extension, `q2 add` compares the
# files against these hashes and refuses (without --force) to overwrite
# local changes.
";

/// Directory depth past which a tree walk gives up. Real extensions are
/// a few levels deep; a deeper tree is almost certainly a symlink loop
/// in a local source.
const MAX_DEPTH: usize = 32;

/// What kind of source an extension was installed from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum SourceKind {
    Github,
    Url,
    LocalArchive,
    LocalDir,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SourceRecord {
    /// Schema version of this file. Bump on an incompatible change.
    pub version: u32,
    /// The source as the user typed it.
    pub source: String,
    pub kind: SourceKind,
    /// The `@ref` of a GitHub source, when one was given.
    #[serde(rename = "ref", default, skip_serializing_if = "Option::is_none")]
    pub git_ref: Option<String>,
    /// Path (relative to the extension directory, `/`-separated) →
    /// lowercase hex sha256. Excludes this record itself.
    pub files: BTreeMap<String, String>,
}

pub const RECORD_VERSION: u32 = 1;

impl SourceRecord {
    pub fn to_yaml(&self) -> Result<String, CommandFailure> {
        let body = serde_yaml::to_string(self).map_err(|e| {
            CommandFailure::new("Failed to serialize the install record", e.to_string())
        })?;
        Ok(format!("{RECORD_HEADER}{body}"))
    }
}

/// What is at an extension's destination, as far as overwriting it is
/// concerned.
#[derive(Debug, PartialEq, Eq)]
pub enum InstalledState {
    /// Nothing is installed there.
    Absent,
    /// Installed with a record, and every file matches it.
    Unmodified,
    /// Installed with a record, and these files differ from it.
    Modified(Vec<LocalEdit>),
    /// Installed without a record (by Quarto 1, or copied by hand), so
    /// local edits cannot be detected.
    Untracked,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LocalEdit {
    pub path: String,
    pub kind: EditKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EditKind {
    Modified,
    Missing,
    Added,
    /// The record itself could not be read, so nothing can be verified.
    UnreadableRecord,
}

impl EditKind {
    pub fn as_str(self) -> &'static str {
        match self {
            EditKind::Modified => "modified",
            EditKind::Missing => "missing",
            EditKind::Added => "added",
            EditKind::UnreadableRecord => "unreadable install record",
        }
    }
}

/// Check an installed extension directory against its record.
pub fn installed_state(dir: &Path) -> Result<InstalledState, CommandFailure> {
    if !dir.exists() {
        return Ok(InstalledState::Absent);
    }
    let record_path = dir.join(RECORD_FILENAME);
    if !record_path.exists() {
        return Ok(InstalledState::Untracked);
    }
    // A record we cannot read is not the same as no record: someone or
    // something changed it, and nothing in the directory can be
    // verified. Treat it as a local edit so `--force` is needed.
    let record = std::fs::read_to_string(&record_path)
        .ok()
        .and_then(|text| serde_yaml::from_str::<SourceRecord>(&text).ok());
    let Some(record) = record else {
        return Ok(InstalledState::Modified(vec![LocalEdit {
            path: RECORD_FILENAME.to_string(),
            kind: EditKind::UnreadableRecord,
        }]));
    };

    let current = hash_tree(dir)?;
    let mut edits = Vec::new();
    for (path, hash) in &record.files {
        match current.get(path) {
            None => edits.push(LocalEdit {
                path: path.clone(),
                kind: EditKind::Missing,
            }),
            Some(h) if h != hash => edits.push(LocalEdit {
                path: path.clone(),
                kind: EditKind::Modified,
            }),
            Some(_) => {}
        }
    }
    for path in current.keys() {
        if !record.files.contains_key(path) {
            edits.push(LocalEdit {
                path: path.clone(),
                kind: EditKind::Added,
            });
        }
    }
    edits.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(if edits.is_empty() {
        InstalledState::Unmodified
    } else {
        InstalledState::Modified(edits)
    })
}

/// sha256 every file under `dir`, keyed by its `/`-separated path
/// relative to `dir`. The record at the top level is excluded.
pub fn hash_tree(dir: &Path) -> Result<BTreeMap<String, String>, CommandFailure> {
    let mut out = BTreeMap::new();
    for rel in list_files(dir)? {
        let key = slash_path(&rel);
        if key == RECORD_FILENAME {
            continue;
        }
        let bytes = std::fs::read(dir.join(&rel)).map_err(|e| {
            CommandFailure::new(
                "Could not read an extension file",
                format!("{}: {e}", dir.join(&rel).display()),
            )
        })?;
        out.insert(key, hex::encode(Sha256::digest(&bytes)));
    }
    Ok(out)
}

/// Every regular file under `dir`, relative to it, sorted. Symlinks are
/// followed (a local source is the user's own tree), bounded by
/// [`MAX_DEPTH`].
pub fn list_files(dir: &Path) -> Result<Vec<PathBuf>, CommandFailure> {
    let mut out = Vec::new();
    walk(dir, Path::new(""), 0, &mut out)?;
    out.sort();
    Ok(out)
}

fn walk(
    root: &Path,
    rel: &Path,
    depth: usize,
    out: &mut Vec<PathBuf>,
) -> Result<(), CommandFailure> {
    let dir = root.join(rel);
    if depth > MAX_DEPTH {
        return Err(CommandFailure::new(
            "Extension directory is nested too deeply",
            format!(
                "{} is more than {MAX_DEPTH} directories deep; a symbolic link may point back \
                 into its own tree.",
                dir.display()
            ),
        ));
    }
    let read_err = |e: std::io::Error| {
        CommandFailure::new(
            "Could not read a directory",
            format!("{}: {e}", dir.display()),
        )
    };
    for entry in std::fs::read_dir(&dir).map_err(read_err)? {
        let entry = entry.map_err(read_err)?;
        let child = rel.join(entry.file_name());
        // `metadata` follows symlinks, so a link is treated as what it
        // points at.
        let meta = std::fs::metadata(root.join(&child)).map_err(read_err)?;
        if meta.is_dir() {
            walk(root, &child, depth + 1, out)?;
        } else if meta.is_file() {
            out.push(child);
        }
    }
    Ok(())
}

/// A relative path with `/` separators on every platform, so a record
/// written on Windows reads the same on Linux.
pub fn slash_path(rel: &Path) -> String {
    rel.components()
        .map(|c| c.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/")
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    fn tree(files: &[(&str, &str)]) -> TempDir {
        let dir = TempDir::new().unwrap();
        for (name, content) in files {
            let path = dir.path().join(name);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, content).unwrap();
        }
        dir
    }

    fn record_for(dir: &Path) -> SourceRecord {
        SourceRecord {
            version: RECORD_VERSION,
            source: "org/repo".into(),
            kind: SourceKind::Github,
            git_ref: None,
            files: hash_tree(dir).unwrap(),
        }
    }

    fn write_record(dir: &Path) {
        let yaml = record_for(dir).to_yaml().unwrap();
        std::fs::write(dir.join(RECORD_FILENAME), yaml).unwrap();
    }

    #[test]
    fn the_record_round_trips_and_starts_with_the_generated_header() {
        let dir = tree(&[
            ("_extension.yml", "title: x\n"),
            ("lua/f.lua", "return {}\n"),
        ]);
        let record = record_for(dir.path());
        let yaml = record.to_yaml().unwrap();
        assert!(
            yaml.starts_with("# Generated by `q2 add`. Do not edit."),
            "{yaml}"
        );
        let parsed: SourceRecord = serde_yaml::from_str(&yaml).unwrap();
        assert_eq!(parsed, record);
        assert_eq!(
            parsed.files.keys().collect::<Vec<_>>(),
            ["_extension.yml", "lua/f.lua"],
            "keys are /-separated on every platform"
        );
        assert!(!yaml.contains("ref:"), "an absent ref is omitted: {yaml}");
    }

    #[test]
    fn hashes_are_sha256_hex() {
        let dir = tree(&[("a.txt", "abc")]);
        assert_eq!(
            hash_tree(dir.path()).unwrap()["a.txt"],
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }

    #[test]
    fn a_missing_directory_is_absent_and_one_without_a_record_is_untracked() {
        let dir = tree(&[("_extension.yml", "x")]);
        assert_eq!(
            installed_state(&dir.path().join("nope")).unwrap(),
            InstalledState::Absent
        );
        assert_eq!(
            installed_state(dir.path()).unwrap(),
            InstalledState::Untracked
        );
    }

    #[test]
    fn an_untouched_install_is_unmodified() {
        let dir = tree(&[("_extension.yml", "x"), ("a/b.lua", "y")]);
        write_record(dir.path());
        assert_eq!(
            installed_state(dir.path()).unwrap(),
            InstalledState::Unmodified
        );
    }

    #[test]
    fn modified_missing_and_added_files_are_all_edits() {
        let dir = tree(&[
            ("_extension.yml", "x"),
            ("keep.lua", "k"),
            ("gone.lua", "g"),
        ]);
        write_record(dir.path());
        std::fs::write(dir.path().join("_extension.yml"), "changed").unwrap();
        std::fs::remove_file(dir.path().join("gone.lua")).unwrap();
        std::fs::write(dir.path().join("new.lua"), "n").unwrap();

        let InstalledState::Modified(edits) = installed_state(dir.path()).unwrap() else {
            panic!("expected edits");
        };
        let got: Vec<(&str, EditKind)> = edits.iter().map(|e| (e.path.as_str(), e.kind)).collect();
        assert_eq!(
            got,
            [
                ("_extension.yml", EditKind::Modified),
                ("gone.lua", EditKind::Missing),
                ("new.lua", EditKind::Added),
            ]
        );
    }

    #[test]
    fn an_unreadable_record_counts_as_an_edit() {
        let dir = tree(&[
            ("_extension.yml", "x"),
            (RECORD_FILENAME, "files: [not, a, map"),
        ]);
        let InstalledState::Modified(edits) = installed_state(dir.path()).unwrap() else {
            panic!("expected edits");
        };
        assert_eq!(edits[0].kind, EditKind::UnreadableRecord);
    }
}
